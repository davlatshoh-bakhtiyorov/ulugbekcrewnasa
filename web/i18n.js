let lang = 'uz';
export const getLang = () => lang;
export const setLang = (l) => { lang = l === 'en' ? 'en' : 'uz'; };

export function t(key, p = {}) {
  const s = D[lang][key] ?? D.uz[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (p[k] ?? ''));
}

/** 12345 -> "12 345" (uz) / "12,345" (en) */
export function num(x, digits = 0) {
  if (x == null || Number.isNaN(x)) return t('lv_unknown');
  const s = Number(x).toFixed(digits);
  const [i, f] = s.split('.');
  const g = i.replace(/\B(?=(\d{3})+(?!\d))/g, lang === 'en' ? ',' : ' ');
  return f ? `${g}${lang === 'en' ? '.' : ','}${f}` : g;
}

/** 'MM-DD' -> "25-aprel" / "25 Apr" */
export function mmdd(s) {
  if (!s) return t('lv_unknown');
  const [m, d] = s.split('-').map(Number);
  return lang === 'en' ? `${d} ${MONTHS.en[m - 1]}` : `${d}-${MONTHS.uz[m - 1]}`;
}

/** '2026-10-16' -> "16-oktabr 2026" / "16 Oct 2026" */
export function fullDate(s) {
  if (!s) return t('lv_unknown');
  const [y, m, d] = s.split('-').map(Number);
  return lang === 'en' ? `${d} ${MONTHS.en[m - 1]} ${y}` : `${d}-${MONTHS.uz[m - 1]} ${y}`;
}

/** '2026-10-16' -> "okt" / "Oct" */
export const monShort = (s) => MON[lang][Number(s.slice(5, 7)) - 1];

/** '2026-03-22' -> "mart" / "Mar" */
export const monthName = (s) => (s ? MONTHS[lang][Number(s.slice(5, 7)) - 1] : '');
